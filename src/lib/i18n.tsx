export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem('versalbank_lang');
      return (saved === 'fr' || saved === 'en') ? saved : 'fr';
    } catch {
      return 'fr';
    }
  });

  useEffect(() => {
    try {
      localStorage.setItem('versalbank_lang', lang);
      document.documentElement.lang = lang;
    } catch (_) {}
  }, [lang]);

  useEffect(() => {
    const handleStorage = (e: StorageEvent) => {
      if (e.key === 'versalbank_lang' && (e.newValue === 'fr' || e.newValue === 'en')) {
        setLangState(e.newValue as Lang);
      }
    };
    const handleCustomEvent = (e: any) => {
      const next = e?.detail;
      if (next === 'fr' || next === 'en') {
        setLangState(next);
      }
    };
    window.addEventListener('storage', handleStorage);
    window.addEventListener('versalbank_lang_change', handleCustomEvent);
    return () => {
      window.removeEventListener('storage', handleStorage);
      window.removeEventListener('versalbank_lang_change', handleCustomEvent);
    };
  }, []);

  const setLang = (newLang: Lang) => {
    setLangState(newLang);
    try {
      localStorage.setItem('versalbank_lang', newLang);
      document.documentElement.lang = newLang;
      window.dispatchEvent(new CustomEvent('versalbank_lang_change', { detail: newLang }));
    } catch (_) {}
  };

  const t = (key: string, variables?: Record<string, string | number>) => {
    const dict = translations[lang] || translations.fr;
    let str = dict[key] || translations.fr[key] || key;
    if (variables) {
      for (const [k, v] of Object.entries(variables)) {
        str = str.replace(new RegExp(`{{${k}}}`, 'g'), String(v));
      }
    }
    return str;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return context;
};
